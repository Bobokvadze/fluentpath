#!/usr/bin/env node
/**
 * Builds js/content/content-index.js: English titles and sizes of all lesson content, so the learning tree and
 * dashboard can show what each lesson is without loading the large content packs.
 * Run after changing grammar/reading/listening/writing/vocabulary content: node scripts/build-content-index.js
 */
'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'js', 'content', 'content-index.js');

function build() {
  const noop = () => {};
  const window = {
    App: { Storage: { get: (p, d) => d, set: noop }, UI: { escapeHTML: (s) => String(s) } },
    document: { readyState: 'complete', addEventListener: noop, getElementById: () => null, querySelector: () => null, querySelectorAll: () => [] },
    addEventListener: noop, setTimeout: () => 0, localStorage: { getItem: () => null }, location: { hash: '' }
  };
  window.window = window;
  const ctx = vm.createContext(Object.assign({}, window, { window }));
  const files = [
    'grammar-a', 'grammar-b', 'grammar-c', 'content/grammar-en-a', 'content/grammar-en-b', 'content/grammar-en-c', 'grammar',
    'reading-a', 'reading-b', 'reading-c', 'reading',
    'listening-a', 'listening-b', 'listening-c1a', 'listening-c1b', 'listening-c1c', 'listening-c', 'listening',
    'writing-a', 'writing-b', 'writing-c', 'writing',
    'content/vocab-a1', 'content/vocab-a2', 'content/vocab-b1', 'content/vocab-b2', 'content/vocab-c1'
  ];
  files.forEach((f) => vm.runInContext(fs.readFileSync(path.join(ROOT, 'js', f + '.js'), 'utf8'), ctx, { filename: f }));

  const A = window.App;
  const index = { grammar: {}, reading: {}, listening: {}, writing: {}, vocabTopics: {} };
  A.Grammar.getAllTopics().forEach((t) => { index.grammar[t.id] = t.titleEn; });
  A.Reading.getAllPassages().forEach((p) => { index.reading[p.id] = p.titleEn; });
  A.Listening.getAllTopics().forEach((t) => { index.listening[t.id] = t.titleEn; });
  A.Writing.getAllTopics().forEach((t) => { index.writing[t.id] = t.titleEn; });
  Object.keys(A.VocabSource).forEach((lvl) => {
    index.vocabTopics[lvl] = {};
    A.VocabSource[lvl].forEach((line) => {
      const topic = line.split('|')[2];
      index.vocabTopics[lvl][topic] = (index.vocabTopics[lvl][topic] || 0) + 1;
    });
  });

  const out = '/**\n * CONTENT-INDEX.JS — generated by scripts/build-content-index.js. Do not edit by hand.\n' +
    ' * English titles of lessons and vocabulary topic sizes, used by the learning tree and dashboard.\n */\n' +
    '(function (window) {\n  "use strict";\n  const App = window.App = window.App || {};\n  App.ContentIndex = ' +
    JSON.stringify(index) + ';\n})(window);\n';
  return { index, out };
}

module.exports = { build, OUT };

if (require.main === module) {
  const { index, out } = build();
  fs.writeFileSync(OUT, out);
  console.log('content-index.js:', Object.keys(index.grammar).length, 'grammar,', Object.keys(index.reading).length, 'reading,',
    Object.keys(index.listening).length, 'listening,', Object.keys(index.writing).length, 'writing;', Math.round(out.length / 1024) + ' KB');
}
