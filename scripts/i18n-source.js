'use strict';
/**
 * Shared helpers for the translation workflow (export-translations.js / import-translations.js).
 * collectSource(): every translatable English string the UI can show a translation for, keyed "section|id|field".
 * loadTranslations(lang) / writeTranslations(lang, table): read and regenerate js/content/i18n-<lang>.js.
 */
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SECTIONS = ['vocab', 'dialogues', 'writing', 'curriculum'];

function sandbox(files) {
  const noop = () => {};
  const window = {
    App: { Storage: { get: (p, d) => d, set: noop }, UI: { escapeHTML: (s) => String(s) } },
    document: { readyState: 'complete', addEventListener: noop, getElementById: () => null, querySelector: () => null, querySelectorAll: () => [] },
    addEventListener: noop, setTimeout: () => 0, localStorage: { getItem: () => null }, location: { hash: '' }
  };
  window.window = window;
  const ctx = vm.createContext(Object.assign({}, window, { window }));
  files.forEach((f) => vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), ctx, { filename: f }));
  return window.App;
}

// key → { en, context }
function collectSource() {
  const App = sandbox(['js/content/i18n.js', 'js/content/vocab-a1.js', 'js/content/vocab-a2.js', 'js/content/vocab-b1.js',
    'js/content/vocab-b2.js', 'js/content/vocab-c1.js', 'js/vocabulary.js', 'js/content/dialogues.js',
    'js/content/writing-en.js', 'js/content/curriculum.js']);
  const out = {};
  const add = (section, id, field, en, context) => { out[section + '|' + id + '|' + field] = { en: en, context: context }; };

  App.Vocabulary.getAllWords().forEach((w) => {
    add('vocab', w.id, 'term', w.word, w.level + ' ' + w.pos + ' — ' + w.def + ' Example: ' + w.ex);
  });
  App.UnitDialogues.forEach((d) => {
    d.lines.forEach((line, i) => add('dialogues', d.id, 'line' + i, line[1], d.level + ' dialogue "' + d.title + '", ' + line[0] + ' speaking'));
  });
  Object.keys(App.WritingEN.tasks).forEach((id) => {
    const t = App.WritingEN.tasks[id];
    add('writing', id, 'task', t.task, 'Writing task instruction. Content points: ' + t.points.join('; '));
  });
  App.CurriculumSpec.levels.forEach((lvl) => {
    lvl.units.forEach((u, i) => {
      const id = lvl.code + '-u' + (i + 1);
      add('curriculum', id, 'title', u.title, lvl.code + ' unit title');
      add('curriculum', id, 'goal', u.goal, lvl.code + ' unit can-do statement (first person)');
    });
  });
  return out;
}

function translationsFile(lang) {
  return path.join(ROOT, 'js', 'content', 'i18n-' + lang + '.js');
}

function loadTranslations(lang) {
  const file = translationsFile(lang);
  if (!fs.existsSync(file)) return {};
  const App = sandbox(['js/content/i18n.js', path.relative(ROOT, file)]);
  return JSON.parse(JSON.stringify((App.I18n && App.I18n[lang]) || {}));
}

function writeTranslations(lang, table) {
  const sorted = {};
  SECTIONS.concat(Object.keys(table).filter((s) => SECTIONS.indexOf(s) === -1)).forEach((section) => {
    const items = table[section] || {};
    sorted[section] = {};
    Object.keys(items).sort().forEach((id) => { sorted[section][id] = items[id]; });
  });
  const body = Object.keys(sorted).map((section) =>
    '  t.' + section + ' = Object.assign(t.' + section + ' || {}, ' + JSON.stringify(sorted[section], null, 2).replace(/\n/g, '\n  ') + ');'
  ).join('\n');
  const out = '/**\n' +
    ' * I18N-' + lang.toUpperCase() + '.JS — translations of educational content (generated by scripts/import-translations.js; edit via that script).\n' +
    ' * Structure: App.I18n.' + lang + '[section][itemId][field] = "translated text".\n' +
    ' *   sections: vocab (term), dialogues (line<N>), writing (task), curriculum (title, goal).\n' +
    ' * Only real translations belong here — leave an item out instead of copying English text.\n' +
    ' * Workflow: node scripts/export-translations.js > to-translate.json, translate the "' + lang + '" fields,\n' +
    ' *           then node scripts/import-translations.js to-translate.json\n' +
    ' */\n' +
    '(function (window) {\n  "use strict";\n  const App = window.App = window.App || {};\n  App.I18n = App.I18n || {};\n' +
    '  const t = App.I18n.' + lang + ' = App.I18n.' + lang + ' || {};\n' + body + '\n})(window);\n';
  fs.writeFileSync(translationsFile(lang), out);
}

module.exports = { ROOT, SECTIONS, collectSource, loadTranslations, writeTranslations };
